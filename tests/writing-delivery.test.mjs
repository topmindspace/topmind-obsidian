import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import * as kernel from '../lib/kernel-api.mjs';
import { prepareWritingDelivery, exportWritingDelivery, isWritingDeliveryCurrent } from '../src/services/writing-delivery.ts';
test('writing exports via the real Kernel, preserves source and rejects stale content', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'tm-writing-vault-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  fs.writeFileSync(path.join(root, 'topmind.yaml'), 'contract_version: 4\nwriteback:\n  mode: auto\n');
  fs.mkdirSync(path.join(root, 'articles'));
  const raw = '# 标题\n\n测试 3 次，通过 2 次。';
  fs.writeFileSync(path.join(root, 'articles/旧公众号稿.md'), raw);
  const { delivery, sourceHash } = await prepareWritingDelivery(root, 'articles/旧公众号稿.md', 'wechat', 'minimal-ink');
  const result = exportWritingDelivery({ kernel, workspaceRoot: root }, 'articles/旧公众号稿.md', sourceHash, delivery);
  assert.equal(result.ok, true); assert.match(fs.readFileSync(path.join(root, result.relativePath), 'utf8'), /通过 2 次/);
  assert.equal(fs.readFileSync(path.join(root, 'articles/旧公众号稿.md'), 'utf8'), raw);
  fs.writeFileSync(path.join(root, 'articles/旧公众号稿.md'), 'edited');
  assert.throws(() => exportWritingDelivery({ kernel, workspaceRoot: root }, 'articles/旧公众号稿.md', sourceHash, delivery), /source-changed/);
});
test('source and local image symlinks cannot leave the vault', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'tm-writing-fence-'));
  const outside = fs.mkdtempSync(path.join(os.tmpdir(), 'tm-writing-outside-'));
  t.after(() => { fs.rmSync(root, { recursive: true, force: true }); fs.rmSync(outside, { recursive: true, force: true }); });
  fs.writeFileSync(path.join(outside, 'secret.md'), 'secret'); fs.symlinkSync(outside, path.join(root, 'escape'));
  await assert.rejects(prepareWritingDelivery(root, 'escape/secret.md', 'wechat', 'minimal-ink'), /outside/);
  fs.writeFileSync(path.join(root, 'note.md'), '![secret](escape/secret.md)');
  const { delivery } = await prepareWritingDelivery(root, 'note.md', 'wechat', 'minimal-ink');
  assert.equal(delivery.images[0].status, 'missing'); assert.doesNotMatch(delivery.html, /c2VjcmV0/);
});
test('image checklist failure returns the saved article and the failed checklist path', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'tm-writing-partial-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  fs.writeFileSync(path.join(root, 'topmind.yaml'), 'contract_version: 4\nwriteback:\n  mode: auto\n');
  const raw = '# Offline index\n\n![Diagram](missing.png)\n';
  fs.writeFileSync(path.join(root, 'note.md'), raw);
  const checklistPath = 'out/note-wechat-images.md';
  fs.mkdirSync(path.join(root, checklistPath), { recursive: true });
  const { delivery, sourceHash } = await prepareWritingDelivery(root, 'note.md', 'wechat', 'minimal-ink');
  const result = exportWritingDelivery({ kernel, workspaceRoot: root }, 'note.md', sourceHash, delivery);
  assert.equal(result.ok, true);
  assert.deepEqual(result.checklist, { relativePath: checklistPath, ok: false });
  assert.equal(fs.readFileSync(path.join(root, result.relativePath), 'utf8'), delivery.html);
  assert.equal(fs.readFileSync(path.join(root, 'note.md'), 'utf8'), raw);
});
test('preview freshness detects an available, modified or removed image by byte hash', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'tm-writing-fresh-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  fs.writeFileSync(path.join(root, 'note.md'), '# Title\n\n![Local diagram](diagram.png)');
  const missing = await prepareWritingDelivery(root, 'note.md', 'wechat', 'minimal-ink');
  assert.equal(isWritingDeliveryCurrent(root, 'note.md', missing), true);
  const image = path.join(root, 'diagram.png');
  fs.writeFileSync(image, Buffer.from('first'));
  assert.equal(isWritingDeliveryCurrent(root, 'note.md', missing), false);
  const ready = await prepareWritingDelivery(root, 'note.md', 'wechat', 'minimal-ink');
  assert.equal(isWritingDeliveryCurrent(root, 'note.md', ready), true);
  fs.writeFileSync(image, Buffer.from('other'));
  assert.equal(isWritingDeliveryCurrent(root, 'note.md', ready), false);
  fs.rmSync(image);
  assert.equal(isWritingDeliveryCurrent(root, 'note.md', ready), false);
  assert.equal(isWritingDeliveryCurrent(root, 'note.md', missing), true);
  fs.writeFileSync(path.join(root, 'note.md'), 'updated');
  assert.equal(isWritingDeliveryCurrent(root, 'note.md', missing), false);
});
